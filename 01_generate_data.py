"""Creates a SIMULATED airline fare dataset (fares.csv).
The data is synthetic - generated by this script - not real airline data.
Say so in your README and in interviews."""
import numpy as np
import pandas as pd

rng = np.random.default_rng(42)
N = 20000

routes = {  # route: (base economy fare in USD, demand level)
    "AUH-LHR": (520, 1.2), "AUH-BOM": (210, 1.4), "AUH-MAA": (230, 1.1),
    "AUH-SIN": (480, 0.9), "AUH-JFK": (780, 1.0), "AUH-SYD": (900, 0.8),
}
route = rng.choice(list(routes), N)
cabin = rng.choice(["Economy", "Business"], N, p=[0.85, 0.15])
travel_date = pd.to_datetime("2025-01-01") + pd.to_timedelta(rng.integers(0, 365, N), unit="D")
days_before = rng.integers(1, 181, N)  # booking window
booking_date = travel_date - pd.to_timedelta(days_before, unit="D")

base = np.array([routes[r][0] for r in route], dtype=float)
demand = np.array([routes[r][1] for r in route])
cabin_mult = np.where(cabin == "Business", 3.2, 1.0)
month = travel_date.month.to_numpy()
season = 1 + 0.25 * np.isin(month, [6, 7, 12]) + 0.10 * np.isin(month, [4, 10])  # peak months
weekend = 1 + 0.06 * (travel_date.dayofweek.to_numpy() >= 4)
advance = 1 + 0.35 * np.exp(-days_before / 25)  # late booking costs more (cheap far out)
fare = base * cabin_mult * season * weekend * advance * (0.9 + 0.1 * demand)
fare = fare * rng.normal(1, 0.06, N)

df = pd.DataFrame({
    "booking_id": np.arange(1, N + 1), "route": route, "cabin": cabin,
    "booking_date": booking_date.date, "travel_date": travel_date.date,
    "days_before_departure": days_before, "fare_usd": fare.round(2),
})
# add realistic mess so the cleaning step has something to do
df.loc[rng.choice(N, 150, replace=False), "fare_usd"] = np.nan
df.loc[rng.choice(N, 40, replace=False), "fare_usd"] = -1
df = pd.concat([df, df.sample(60, random_state=1)], ignore_index=True)  # duplicates
df.to_csv("fares.csv", index=False)
print("fares.csv written:", len(df), "rows")
